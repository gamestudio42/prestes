"""Original 16 x 16 pixel icons for the Prestes interface.

Draws every icon on a 16 x 16 grid (geometric ones from primitives, figures by
hand), writes them to `assets/icons/icons.txt` (one `== name` block of 16 rows,
`#` filled, `.` empty) and an enlarged preview sheet for review. The Aseprite
source is built from the text file by `build-icons.lua`; after that the
`.aseprite` file is the one to edit.

Run: python tools/icons/icon_grids.py
"""
from __future__ import annotations

import math
import os
import sys

N = 16
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


class Grid:
    def __init__(self) -> None:
        self.px = [[0] * N for _ in range(N)]

    def set(self, x: int, y: int, on: int = 1) -> "Grid":
        if 0 <= x < N and 0 <= y < N:
            self.px[y][x] = on
        return self

    def line(self, x0: int, y0: int, x1: int, y1: int) -> "Grid":
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            self.set(x0, y0)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy
        return self

    def rect(self, x: int, y: int, w: int, h: int, fill: bool = False) -> "Grid":
        for j in range(h):
            for i in range(w):
                if fill or i in (0, w - 1) or j in (0, h - 1):
                    self.set(x + i, y + j)
        return self

    def circle(self, cx: float, cy: float, r: float, fill: bool = False) -> "Grid":
        for y in range(N):
            for x in range(N):
                d = math.hypot(x - cx, y - cy)
                if (fill and d <= r + 0.3) or (not fill and abs(d - r) < 0.55):
                    self.set(x, y)
        return self

    def clear(self, x: int, y: int, w: int = 1, h: int = 1) -> "Grid":
        for j in range(h):
            for i in range(w):
                self.set(x + i, y + j, 0)
        return self

    def art(self, rows: str, ox: int = 0, oy: int = 0) -> "Grid":
        lines = [line for line in rows.strip("\n").splitlines()]
        for j, line in enumerate(lines):
            for i, ch in enumerate(line.strip()):
                if ch == "#":
                    self.set(ox + i, oy + j)
                elif ch == "x":
                    self.set(ox + i, oy + j, 0)
        return self


def grid_from(rows: str) -> Grid:
    g = Grid()
    lines = rows.strip("\n").splitlines()
    assert len(lines) == N, f"{len(lines)} rows"
    for j, line in enumerate(lines):
        line = line.strip()
        assert len(line) == N, f"row {j}: {line!r} has {len(line)}"
        for i, ch in enumerate(line):
            g.px[j][i] = 1 if ch == "#" else 0
    return g


ICONS: dict[str, Grid] = {}


def icon(name: str):
    def wrap(fn):
        ICONS[name] = fn()
        return fn
    return wrap


