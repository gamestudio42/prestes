def write() -> None:
    out_dir = os.path.join(ROOT, "assets", "icons")
    os.makedirs(out_dir, exist_ok=True)
    lines: list[str] = []
    for name, g in ICONS.items():
        lines.append(f"== {name}")
        for row in g.px:
            lines.append("".join("#" if v else "." for v in row))
    with open(os.path.join(out_dir, "icons.txt"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")

    try:
        from PIL import Image, ImageDraw
    except ImportError:
        return
    cols = 8
    cell = 16 * 4 + 24
    rows = math.ceil(len(ICONS) / cols)
    sheet = Image.new("RGB", (cols * cell, rows * (cell + 14)), (42, 31, 20))
    draw = ImageDraw.Draw(sheet)
    for index, (name, g) in enumerate(ICONS.items()):
        ox = (index % cols) * cell + 12
        oy = (index // cols) * (cell + 14) + 8
        for y in range(N):
            for x in range(N):
                if g.px[y][x]:
                    draw.rectangle([ox + x * 4, oy + y * 4, ox + x * 4 + 3, oy + y * 4 + 3], fill=(239, 226, 196))
        draw.text((ox - 8, oy + 16 * 4 + 4), name[:16], fill=(224, 184, 90))
    preview = sys.argv[1] if len(sys.argv) > 1 else os.path.join(out_dir, "preview.png")
    sheet.save(preview)


if __name__ == "__main__":
    write()
    print(f"{len(ICONS)} icons")
