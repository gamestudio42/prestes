import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileMapDocument, fromMapDocument, parseMapDocumentText, setActiveMap, validateEditableMap, validateMapRosters, validatePositions, type AuthoredMapEntry } from '../packages/shared/src';
import { CAMPAIGN_CHAPTERS, validateMapCommander } from '../packages/content/src';

/**
 * add-map-editor: checks every authored map document in
 * packages/shared/src/maps/authored/ (parse, compile, validate) and
 * regenerates the folder's index.ts so the catalog registers them.
 * `--write-index` only rewrites the index (the editor's save does this).
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const AUTHORED_DIR = resolve(root, 'packages/shared/src/maps/authored');
const MAX_BYTES = 2 * 1024 * 1024;

export function authoredFiles(dir = AUTHORED_DIR): string[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.map.json'))
    .sort();
}

export const PREVIEW_DIR = resolve(root, 'apps/game/public/maps');

/** author-game-maps D2: a map's index entry, read from its file (null when it does not parse). */
function entryOf(dir: string, file: string, previews: string): AuthoredMapEntry | null {
  const parsed = parseMapDocumentText(readFileSync(resolve(dir, file), 'utf8'));
  if (!parsed.ok) return null;
  const { id, use, mission, size, name, description } = parsed.document;
  return { id, use, ...(mission ? { mission } : {}), size, name, description, preview: existsSync(resolve(previews, `${id}.png`)) };
}

/** author-game-maps 4.2: every map in the folder as the index lists it (read now, not from the generated index). */
export function authoredEntries(dir = AUTHORED_DIR, previews = PREVIEW_DIR): AuthoredMapEntry[] {
  return authoredFiles(dir)
    .map((file) => entryOf(dir, file, previews))
    .filter((entry): entry is AuthoredMapEntry => entry !== null);
}

/**
 * The index: what the menus know of each map (names, slot, size), and every
 * map as a loader, so no map document is in the game or worker bundles until
 * a battle asks for it.
 */
export function indexSource(files: readonly string[], dir = AUTHORED_DIR, previews = PREVIEW_DIR): string {
  const entries = files.map((file) => entryOf(dir, file, previews)).filter((entry): entry is AuthoredMapEntry => entry !== null);
  const list = entries.map((entry) => `  ${JSON.stringify(entry)},`).join('\n');
  const loaders = files
    .map((file) => `  '${basename(file, '.map.json')}': () => import('./${file}').then((module) => module.default as unknown as MapDocument),`)
    .join('\n');
  return [
    '// Generated by tools/check-maps.ts from the *.map.json files in this folder. Do not edit.',
    "import type { AuthoredMapEntry, MapDocument } from '../document';",
    '',
    '/** What the menus know of every authored map, without loading it. */',
    entries.length === 0
      ? 'export const AUTHORED_MAP_INDEX: readonly AuthoredMapEntry[] = [];'
      : `export const AUTHORED_MAP_INDEX: readonly AuthoredMapEntry[] = [\n${list}\n];`,
    '',
    '/** Every authored map, loaded on demand (no map document is in the bundles). */',
    files.length === 0
      ? 'export const AUTHORED_MAP_LOADERS: Readonly<Record<string, () => Promise<MapDocument>>> = {};'
      : `export const AUTHORED_MAP_LOADERS: Readonly<Record<string, () => Promise<MapDocument>>> = {\n${loaders}\n};`,
    '',
  ].join('\n');
}

export function writeIndex(dir = AUTHORED_DIR, previews = PREVIEW_DIR): boolean {
  const path = resolve(dir, 'index.ts');
  const next = indexSource(authoredFiles(dir), dir, previews);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') === next) return false;
  writeFileSync(path, next);
  return true;
}

/** make-campaign-playable D7: `only` checks one map in full (ids and missions are still checked across all). */
export function checkAuthoredMaps(dir = AUTHORED_DIR, only?: string): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  const missions = new Map<string, string>();
  for (const file of authoredFiles(dir)) {
    const path = resolve(dir, file);
    if (statSync(path).size > MAX_BYTES) errors.push(`${file}: larger than 2 MB`);
    const parsed = parseMapDocumentText(readFileSync(path, 'utf8'));
    if (!parsed.ok) {
      errors.push(`${file}: ${parsed.error} (${parsed.detail})`);
      continue;
    }
    const { document } = parsed;
    if (`${document.id}.map.json` !== file) errors.push(`${file}: id ${document.id} does not match the file name`);
    if (ids.has(document.id)) errors.push(`${file}: duplicate id ${document.id}`);
    ids.add(document.id);
    // author-game-maps D1: one map per campaign mission.
    if (document.use === 'campaign' && document.mission) {
      const other = missions.get(document.mission);
      if (other) errors.push(`${file}: mission ${document.mission} already has the map ${other}`);
      else missions.set(document.mission, document.id);
    }
    if (only !== undefined && document.id !== only) continue;
    // add-historical-commander 1.3: the commander is the chapter's, registered and playable.
    for (const error of validateMapCommander(document, CAMPAIGN_CHAPTERS)) errors.push(`${file}: ${error}`);
    for (const problem of validateEditableMap(fromMapDocument(document))) {
      if (problem.severity === 'error') errors.push(`${file}: ${problem.code} ${JSON.stringify(problem.params)}`);
      // Warnings (masked vegetation, a cover gap) are shown and do not fail the check.
      else console.warn(`warning ${file}: ${problem.code} ${JSON.stringify(problem.params)}`);
    }
    // author-game-maps: every position's entrance on open ground and reachable (a door against a fence).
    const compiled = compileMapDocument(document);
    setActiveMap(compiled);
    for (const error of validatePositions(compiled)) errors.push(`${file}: ${error}`);
    // Its enemy presets are valid legalist rosters, and every section type deploys in every slot.
    for (const error of validateMapRosters(compiled)) errors.push(`${file}: ${error}`);
  }
  return errors;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rewritten = writeIndex();
  if (process.argv.includes('--write-index')) {
    console.log(rewritten ? 'Authored map index rewritten.' : 'Authored map index up to date.');
  } else {
    // make-campaign-playable D7: `--map <id>` checks one map (maps:accept).
    const mapIndex = process.argv.indexOf('--map');
    const only = mapIndex >= 0 ? process.argv[mapIndex + 1] : undefined;
    if (mapIndex >= 0 && (!only || !authoredFiles().includes(`${only}.map.json`))) {
      console.error(`unknown authored map: ${only ?? '(none)'}`);
      process.exit(1);
    }
    const errors = checkAuthoredMaps(AUTHORED_DIR, only);
    if (errors.length > 0) {
      for (const error of errors) console.error(error);
      process.exit(1);
    }
    console.log(only ? `Map check passed: ${only}.` : `Map check passed: ${authoredFiles().length} authored maps${rewritten ? ' (index rewritten)' : ''}.`);
  }
}
