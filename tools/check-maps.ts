import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { basename, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromMapDocument, parseMapDocumentText, setActiveMap, validateEditableMap, VILA_MILITAR } from '../packages/shared/src';

/**
 * add-map-editor: checks every authored map document in
 * packages/shared/src/maps/authored/ (parse, compile, validate) and
 * regenerates the folder's index.ts so the catalog registers them.
 * `--write-index` only rewrites the index (the editor's save does this).
 */

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const AUTHORED_DIR = resolve(root, 'packages/shared/src/maps/authored');
const MAX_BYTES = 2 * 1024 * 1024;

export function authoredFiles(dir = AUTHORED_DIR): string[] {
  return readdirSync(dir)
    .filter((name) => name.endsWith('.map.json'))
    .sort();
}

function identifier(file: string): string {
  return basename(file, '.map.json').replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase()) + 'Map';
}

/** Whether a map file is a skirmish map (the menu lists it, so it ships in the bundle). */
function isSkirmish(dir: string, file: string): boolean {
  try {
    return (JSON.parse(readFileSync(resolve(dir, file), 'utf8')) as { use?: unknown }).use === 'skirmish';
  } catch {
    return false;
  }
}

/**
 * The index: skirmish maps imported eagerly (the menu lists them), every map
 * also as a loader, so campaign maps stay out of the game and worker bundles
 * until a battle asks for them.
 */
export function indexSource(files: readonly string[], dir = AUTHORED_DIR): string {
  const skirmish = files.filter((file) => isSkirmish(dir, file));
  const imports = skirmish.map((file) => `import ${identifier(file)} from './${file}';`).join('\n');
  const list = skirmish.map((file) => `  ${identifier(file)} as unknown as MapDocument,`).join('\n');
  const loaders = files
    .map((file) => `  '${basename(file, '.map.json')}': () => import('./${file}').then((module) => module.default as unknown as MapDocument),`)
    .join('\n');
  return [
    '// Generated by tools/check-maps.ts from the *.map.json files in this folder. Do not edit.',
    "import type { MapDocument } from '../document';",
    ...(imports ? [imports] : []),
    '',
    '/** The skirmish maps, in the bundle: the menu lists them. */',
    skirmish.length === 0
      ? 'export const AUTHORED_SKIRMISH_DOCUMENTS: readonly MapDocument[] = [];'
      : `export const AUTHORED_SKIRMISH_DOCUMENTS: readonly MapDocument[] = [\n${list}\n];`,
    '',
    '/** Every authored map, loaded on demand (campaign maps stay out of the bundles). */',
    files.length === 0
      ? 'export const AUTHORED_MAP_LOADERS: Readonly<Record<string, () => Promise<MapDocument>>> = {};'
      : `export const AUTHORED_MAP_LOADERS: Readonly<Record<string, () => Promise<MapDocument>>> = {\n${loaders}\n};`,
    '',
  ].join('\n');
}

export function writeIndex(dir = AUTHORED_DIR): boolean {
  const path = resolve(dir, 'index.ts');
  const next = indexSource(authoredFiles(dir), dir);
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') === next) return false;
  writeFileSync(path, next);
  return true;
}

export function checkAuthoredMaps(dir = AUTHORED_DIR): string[] {
  const errors: string[] = [];
  const ids = new Set<string>();
  for (const file of authoredFiles(dir)) {
    const path = resolve(dir, file);
    if (statSync(path).size > MAX_BYTES) errors.push(`${file}: larger than 2 MB`);
    const parsed = parseMapDocumentText(readFileSync(path, 'utf8'));
    if (!parsed.ok) {
      errors.push(`${file}: ${parsed.error} (${parsed.detail})`);
      continue;
    }
    const { document } = parsed;
    if (`${document.id}.map.json` !== file) errors.push(`${file}: id ${document.id} does not match the file name`);
    if (ids.has(document.id)) errors.push(`${file}: duplicate id ${document.id}`);
    ids.add(document.id);
    if (['vila-militar', 'fazenda', 'serra-rio', 'bairro'].includes(document.id)) errors.push(`${file}: id ${document.id} is a hand-written map's`);
    for (const problem of validateEditableMap(fromMapDocument(document))) {
      if (problem.severity === 'error') errors.push(`${file}: ${problem.code} ${JSON.stringify(problem.params)}`);
    }
  }
  setActiveMap(VILA_MILITAR);
  return errors;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const rewritten = writeIndex();
  if (process.argv.includes('--write-index')) {
    console.log(rewritten ? 'Authored map index rewritten.' : 'Authored map index up to date.');
  } else {
    const errors = checkAuthoredMaps();
    if (errors.length > 0) {
      for (const error of errors) console.error(error);
      process.exit(1);
    }
    console.log(`Map check passed: ${authoredFiles().length} authored maps${rewritten ? ' (index rewritten)' : ''}.`);
  }
}
